"""Wire protocol between the laptop server and the clients.

/ws/glasses  — the Even Hub app (apps/g2). Server-driven UI: the app is a dumb
               terminal that renders containers it is told to and forwards input.
               Text frames = JSON messages below. Binary frames (client->server) =
               raw 16 kHz s16le mono PCM, only between AudioStart and AudioEnd.
/ws/camera   — the iPhone camera page (apps/camera). First text frame = CameraHello,
               then each binary frame is one JPEG.

The TypeScript mirror lives in apps/g2/src/protocol.ts and is generated by
scripts/gen_contracts.py. Never hand-edit the TS file.
"""

from __future__ import annotations

from typing import Annotated, Literal

from pydantic import BaseModel, Field, TypeAdapter, model_validator

PROTOCOL_VERSION = 1

# ---------------------------------------------------------------- display model
# Mirrors Even Hub SDK containers (sdk 0.0.16). Limits: <=4 image + <=8 text/list,
# exactly one capture container, image 20..288 x 20..144, text <=1000 chars on page build.


class Container(BaseModel):
    id: int
    name: str = Field(max_length=16)
    x: int = Field(ge=0, le=576)
    y: int = Field(ge=0, le=288)
    w: int = Field(ge=0, le=576)
    h: int = Field(ge=0, le=288)
    z: int | None = None  # zOrderIndex; if any container sets it, all must

    @model_validator(mode="after")
    def _on_canvas(self):
        if self.x + self.w > 576 or self.y + self.h > 288:
            raise ValueError(f"{self.name}: box exceeds 576x288 canvas")
        return self


class TextBox(Container):
    kind: Literal["text"] = "text"
    content: str = Field(default="", max_length=1000)
    capture: bool = False  # isEventCapture
    border: int = Field(default=0, ge=0, le=5)
    border_color: int = Field(default=15, ge=0, le=15)
    radius: int = Field(default=0, ge=0, le=10)
    padding: int = Field(default=0, ge=0, le=32)
    brightness: int | None = Field(default=None, ge=0, le=4)  # textColor


class ListBox(Container):
    kind: Literal["list"] = "list"
    items: list[Annotated[str, Field(max_length=64)]] = Field(max_length=20)
    capture: bool = False
    border: int = Field(default=0, ge=0, le=5)
    border_color: int = Field(default=15, ge=0, le=15)
    radius: int = Field(default=0, ge=0, le=10)
    padding: int = Field(default=0, ge=0, le=32)


class ImageBox(Container):
    kind: Literal["image"] = "image"
    w: int = Field(ge=20, le=288)
    h: int = Field(ge=20, le=144)


AnyBox = Annotated[TextBox | ListBox | ImageBox, Field(discriminator="kind")]


# ------------------------------------------------------------ server -> glasses


class ShowPage(BaseModel):
    """Full layout. Client calls createStartUpPageContainer the first time, then
    rebuildPageContainer (~165 ms, may flicker). Use sparingly."""

    type: Literal["page"] = "page"
    boxes: list[AnyBox]

    @model_validator(mode="after")
    def _sdk_limits(self):
        # Same rules the SDK enforces (it rejects the page otherwise); failing here gives a Python traceback instead.
        n_img = sum(b.kind == "image" for b in self.boxes)
        if n_img > 4 or len(self.boxes) - n_img > 8:
            raise ValueError("max 4 image + 8 text/list boxes")
        if sum(getattr(b, "capture", False) for b in self.boxes) != 1:
            raise ValueError("exactly one box must have capture=True")
        for attr in ("id", "name"):
            vals = [getattr(b, attr) for b in self.boxes]
            if len(set(vals)) != len(vals):
                raise ValueError(f"duplicate box {attr}")
        zs = [b.z for b in self.boxes]
        if any(z is not None for z in zs) and (None in zs or len(set(zs)) != len(zs)):
            raise ValueError("z: set on all boxes or none, and unique")
        return self


class SetText(BaseModel):
    """In-place text update (textContainerUpgrade, ~83 ms, no flicker)."""

    type: Literal["text"] = "text"
    id: int
    name: str
    content: str = Field(max_length=2000)
    brightness: int | None = Field(default=None, ge=0, le=4)


class SetImage(BaseModel):
    """PNG (greyscale, exact container size) as base64. Client sends sequentially;
    ~104 ms + ~3.9 ms/KB each, so <= ~9 updates/s total across all image boxes."""

    type: Literal["image"] = "image"
    id: int
    name: str
    png_b64: str
    t: float | None = None  # server time.time() when produced; client echoes it in Drawn


class Control(BaseModel):
    type: Literal["control"] = "control"
    mic: bool | None = None  # audioControl(on, Glasses)
    imu_pace: int | None = Field(default=None, ge=0, le=1000, multiple_of=100)  # 0 = off, else ImuReportPace code
    exit: bool = False  # shutDownPageContainer(1) (system confirm dialog)


class Pong(BaseModel):
    type: Literal["pong"] = "pong"
    t: float


ServerMsg = Annotated[ShowPage | SetText | SetImage | Control | Pong, Field(discriminator="type")]

# ------------------------------------------------------------ glasses -> server

InputKind = Literal["tap", "double_tap", "scroll_up", "scroll_down", "long_press", "long_press_release", "list_select"]


class Hello(BaseModel):
    type: Literal["hello"] = "hello"
    protocol: int = PROTOCOL_VERSION
    client: Literal["g2", "sim"] = "g2"
    device: dict = {}  # getDeviceInfo() passthrough


class Input(BaseModel):
    type: Literal["input"] = "input"
    kind: InputKind
    source: Literal["right", "left", "ring", "unknown"] = "unknown"
    container: str | None = None
    index: int | None = None  # list_select only
    t: float  # client epoch seconds


class AudioStart(BaseModel):
    type: Literal["audio_start"] = "audio_start"
    utterance: str  # client-generated id


class AudioEnd(BaseModel):
    type: Literal["audio_end"] = "audio_end"
    utterance: str


class Imu(BaseModel):
    """Raw SDK imuData. Units/axes are undocumented — Part 3 owns characterising them."""

    type: Literal["imu"] = "imu"
    x: float
    y: float
    z: float
    t: float


class Lifecycle(BaseModel):
    type: Literal["lifecycle"] = "lifecycle"
    event: Literal["foreground", "background", "abnormal_exit", "system_exit"]
    t: float


class DeviceStatus(BaseModel):
    type: Literal["status"] = "status"
    battery: int | None = None
    wearing: bool | None = None
    charging: bool | None = None


class Ping(BaseModel):
    type: Literal["ping"] = "ping"
    t: float


class Drawn(BaseModel):
    """Ack that a SetImage was actually drawn (superseded/coalesced images are never acked)."""

    type: Literal["drawn"] = "drawn"
    id: int
    name: str
    t: float | None = None  # echo of SetImage.t
    ms: float  # duration of the SDK updateImageRawData call, measured on the phone


ClientMsg = Annotated[
    Hello | Input | AudioStart | AudioEnd | Imu | Lifecycle | DeviceStatus | Ping | Drawn, Field(discriminator="type")
]

# --------------------------------------------------------------- camera client


class CameraHello(BaseModel):
    type: Literal["camera_hello"] = "camera_hello"
    camera_id: str  # e.g. "scene" (Part 2/3 default)
    width: int
    height: int
    fps: float
    device: str = ""  # navigator.userAgent


# ---------------------------------------------------------- in-process hub events
# Published on bluebook_core.hub. Not sent over the wire.


class CameraFrame(BaseModel):
    """Latest JPEG from an iPhone camera. Published with session=camera_id, so
    hub.last(CameraFrame, "scene") is the newest scene frame. `t` = server receive time."""

    session: str  # == camera_id
    t: float
    jpeg: bytes
    width: int
    height: int


class ImuSample(BaseModel):
    """Every glasses Imu message, re-published per session (IMU is off until someone sends Control(imu_pace))."""

    session: str
    x: float
    y: float
    z: float
    t: float


class ImageDrawn(BaseModel):
    """Every glasses Drawn ack, re-published per session. Lets parts flow-control overlays to the
    glasses' real rate and measure latency (at - t = server->glasses->drawn round trip)."""

    session: str
    id: int
    name: str
    t: float | None = None
    ms: float
    at: float  # server receive time


class StepTarget(BaseModel):
    object_id: str
    name: str
    aliases: list[str] = []
    visual_description: str = ""
    action: str = ""


class StepChanged(BaseModel):
    """Part 2 -> Part 3: the user is now on this step. Empty targets = clear overlay."""

    session: str
    skill_id: str
    step_id: str | None  # None = not in a step (library, done)
    targets: list[StepTarget] = []


class SceneObservation(BaseModel):
    """Part 3 -> Part 2 (optional): what is where right now, in scene-camera pixels."""

    session: str
    camera_id: str
    t: float
    objects: dict[str, tuple[float, float, float, float]]  # object_id -> normalised box x0,y0,x1,y1
    head_visible: bool = False  # wearer's head pose currently tracked (marker-free, DESIGN §6.3)


class Arrow(BaseModel):
    kind: Literal["arrow"] = "arrow"
    x0: float
    y0: float
    x1: float
    y1: float  # display px, tip at (x1, y1)


class Rect(BaseModel):
    kind: Literal["rect"] = "rect"
    x0: float
    y0: float
    x1: float
    y1: float


class Ring(BaseModel):
    kind: Literal["ring"] = "ring"
    cx: float
    cy: float
    r: float


class Label(BaseModel):
    kind: Literal["label"] = "label"
    x: float
    y: float
    text: str


Primitive = Annotated[Arrow | Rect | Ring | Label, Field(discriminator="kind")]


class OverlayFrame(BaseModel):
    """Part 3 -> core compositor: primitives in glasses display px (576x288 canvas).
    Empty list clears the overlay. `t` = timestamp of the camera frame it was computed from."""

    session: str
    t: float
    primitives: list[Primitive] = []


server_msg = TypeAdapter(ServerMsg)
client_msg = TypeAdapter(ClientMsg)
