"""Regenerate contracts from the Python source of truth.

    uv run python scripts/gen_contracts.py

Writes contracts/*.schema.json and apps/g2/src/protocol.ts. CI/reviewers: a diff here
means the contract changed — follow docs/INTEGRATION.md §Contract changes.
"""

import json
import subprocess
from pathlib import Path

from bluebook_core.protocol import CameraHello, ClientMsg, ServerMsg
from bluebook_core.skill import SkillPackage
from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import GenerateJsonSchema

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "contracts"


class NoFieldTitles(GenerateJsonSchema):
    """Field titles make json-schema-to-typescript emit one alias per field (`type Id1 = number`)."""

    def field_title_should_be_set(self, schema) -> bool:
        return False


class Protocol(BaseModel):
    """Wrapper so one schema file holds every wire message."""

    server: ServerMsg
    client: ClientMsg
    camera_hello: CameraHello


def require_discriminators(schema: dict) -> dict:
    """`type`/`kind` have defaults in Python but must be required in TS for union narrowing."""
    for d in schema.get("$defs", {}).values():
        for key in ("type", "kind"):
            if "const" in d.get("properties", {}).get(key, {}):
                d.setdefault("required", []).insert(0, key)
    return schema


def main() -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "skill.schema.json").write_text(
        json.dumps(TypeAdapter(SkillPackage).json_schema(schema_generator=NoFieldTitles), indent=2) + "\n"
    )
    (OUT / "protocol.schema.json").write_text(
        json.dumps(require_discriminators(Protocol.model_json_schema(schema_generator=NoFieldTitles)), indent=2) + "\n"
    )
    ts = subprocess.run(
        [
            "pnpm",
            "dlx",
            "json-schema-to-typescript@15.0.4",
            "-i",
            str(OUT / "protocol.schema.json"),
            "--additionalProperties=false",
            "--maxItems=-1",
            "--bannerComment",
            "/* GENERATED by scripts/gen_contracts.py — do not edit */",
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    (ROOT / "apps/g2/src/protocol.ts").write_text(ts)
    print("contracts regenerated")


if __name__ == "__main__":
    main()
